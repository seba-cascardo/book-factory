#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Coverage accounting — how much of the eligible surface a round actually saw.

## Why this exists

v3.1's verdict was `f(findings)`. Nothing in it knew how many candidates were
never looked at, so a book could reach `PASS` → `phase: complete` having audited
30 of 474 candidate rules, and the "two consecutive quiet rounds" criterion was
satisfied *by construction*: rounds 2+ re-audited the same 30 and therefore
produced no new findings, forever. The quota was documented as a cost dial and
behaved as a permanent ceiling.

Three files already told the truth at dossier level — the rule auditor's *"do not
conclude the rule is clean"*, the findings schema's *"a sampled run may never be
reported as clean"*, the report template's copy of the same line. The verdict did
not know. This module is what tells it.

## Two definitions that are fixed and do not move

**`eligible_candidates` is post-filter, not raw.** It counts what survives the
deterministic filters — `--min-instances`, `--df-ceiling`, the discard of
imperatives and voice, the `--min-units` span floor. Put noise in the denominator
and the percentage inflates itself, and it inflates in the comfortable direction.

**`sampled_within` is not `selected`.** Coverage has two axes: breadth (how many
subjects were audited) and depth (how many instances per subject). A rule with
more instances than an agent can judge in one run ships flagged `tractable:
false` and can only be SAMPLED. A run with 100% breadth and 15% depth is not a
complete run, and reporting one number hides the other.

## The ledger

`reviews/manuscript-gate-<date>/audited.yaml` is cumulative across rounds and
keyed by subject id **and fingerprint**. It is what lets round N+1 audit the next
slice of the pool instead of re-auditing round N's, and what sends a subject back
to the queue when its text was edited. Without it the quota is a ceiling; with
it, it is the cost dial its comment always claimed to be.
"""

from __future__ import annotations

import hashlib
import json
import sys
from dataclasses import dataclass, field
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover - environment guard
    sys.exit("Missing PyYAML. Install with: pip install pyyaml")


def composite_fingerprint(parts: list[str]) -> str:
    """One id over everything an audit of this subject actually read.

    Not just the rule sentence or the concept name: the instances and passages
    too. An auditor judged a rule AGAINST its instances, so an edit to any of
    them makes that judgement stale — and a subject whose fingerprint moved goes
    back into the pool rather than staying filed as covered.

    The order is normalized, so re-ordering alone does not re-queue anything.
    """
    joined = "\n".join(sorted(p for p in parts if p))
    return hashlib.sha1(joined.encode("utf-8")).hexdigest()[:12]


@dataclass
class Subject:
    """One auditable unit of a semantic check: a rule, or a concept."""
    id: str
    fingerprint: str
    stratum: str = ""
    rank: int = 0
    instances: int = 0
    # Depth flag. True when the emitted file is a SAMPLE of the subject rather
    # than all of it — `tractable: false` for a rule, a trimmed home unit for a
    # concept dossier.
    sampled: bool = False

    def as_dict(self) -> dict:
        return {"id": self.id, "fingerprint": self.fingerprint,
                "stratum": self.stratum, "rank": self.rank,
                "instances": self.instances, "sampled": self.sampled}


# ---------------------------------------------------------------------------
# The ledger
# ---------------------------------------------------------------------------


def load_ledger(path: str | Path | None) -> dict[str, dict[str, dict]]:
    """`{check: {subject_id: {fingerprint, sampled, round}}}`; {} when absent."""
    if not path:
        return {}
    p = Path(path)
    if not p.exists():
        return {}
    doc = yaml.safe_load(p.read_text(encoding="utf-8")) or {}
    checks = doc.get("checks") or {}
    return {k: dict(v or {}) for k, v in checks.items()}


def save_ledger(path: str | Path, checks: dict[str, dict[str, dict]]) -> None:
    doc = {
        "# generated by": "scripts/manuscript_gate.py — cumulative across rounds",
        "# what it is": ("what each semantic check has already audited, keyed by "
                         "subject id AND fingerprint. A subject whose text changed "
                         "no longer matches and goes back into the pool."),
        "# do not hand-edit": ("delete the file to re-audit everything from scratch; "
                               "editing an entry to claim coverage that never happened "
                               "is the one lie this whole design exists to prevent."),
        "schema_version": "1.0",
        "checks": {k: dict(sorted(v.items())) for k, v in sorted(checks.items())},
    }
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(yaml.safe_dump(doc, allow_unicode=True, sort_keys=False, width=200),
                 encoding="utf-8")


def partition(subjects: list[Subject], audited: dict[str, dict]
              ) -> tuple[list[Subject], list[str], list[str]]:
    """Split the eligible pool against the ledger.

    Returns `(pool, already_audited_ids, requeued_ids)`:

      - **pool** — what this round may select from: never audited, or audited
        under a fingerprint that no longer matches.
      - **already_audited** — audited, text unchanged. Out of the pool, but
        still in the denominator: a covered candidate is covered, and shrinking
        the denominator would manufacture the completeness this measures.
      - **requeued** — audited before, text edited since. Back in the pool. This
        is propagation for rules and concepts: the same asymmetry the claim
        index uses, applied to the audit ledger.
    """
    pool: list[Subject] = []
    already: list[str] = []
    requeued: list[str] = []
    for s in subjects:
        prior = audited.get(s.id)
        if prior and prior.get("fingerprint") == s.fingerprint:
            already.append(s.id)
            continue
        if prior:
            requeued.append(s.id)
        pool.append(s)
    return pool, sorted(already), sorted(requeued)


# ---------------------------------------------------------------------------
# The per-check record
# ---------------------------------------------------------------------------


@dataclass
class CoverageRecord:
    check: str
    round: int = 1
    eligible_candidates: int = 0
    selected: int = 0
    emitted: int = 0
    sampled_within: int = 0
    already_audited: list[str] = field(default_factory=list)
    requeued: list[str] = field(default_factory=list)
    strata: dict[str, dict[str, int]] = field(default_factory=dict)
    subjects: list[Subject] = field(default_factory=list)
    cut: list[dict] = field(default_factory=list)
    note: str = ""

    def as_dict(self) -> dict:
        return {
            "check": self.check,
            "round": self.round,
            "eligible_candidates": self.eligible_candidates,
            "selected": self.selected,
            "emitted": self.emitted,
            "sampled_within": self.sampled_within,
            "already_audited": self.already_audited,
            "requeued": self.requeued,
            "strata": self.strata,
            "subjects": [s.as_dict() for s in self.subjects],
            "cut": self.cut,
            "note": self.note or (
                "eligible_candidates is POST-FILTER. sampled_within is the depth axis "
                "and is not the same number as selected — a run with full breadth and "
                "partial depth is not a complete run."),
        }

    def write(self, path: str | Path) -> None:
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(self.as_dict(), indent=2, ensure_ascii=False),
                     encoding="utf-8")

    def report_line(self, noun: str) -> str:
        seen = len(self.already_audited) + self.selected
        depth = f" ({self.sampled_within} sampled)" if self.sampled_within else ""
        tail = ""
        if self.requeued:
            tail = f" · {len(self.requeued)} re-queued (text edited since it was audited)"
        return (f"{self.check} coverage: {seen}/{self.eligible_candidates} "
                f"{noun}(s){depth}{tail}")


def coverage_path(round_dir: str | Path, check: str) -> Path:
    return Path(round_dir) / f"coverage-{check}.json"


def add_coverage_args(parser) -> None:
    """The two flags every subject-emitting script accepts."""
    parser.add_argument(
        "--coverage", metavar="PATH", default=None,
        help="Write the coverage record here (round-N/coverage-<check>.json). The "
             "gate's verdict reads it: without it the verdict cannot know how much "
             "of the surface was never looked at.")
    parser.add_argument(
        "--audited", metavar="PATH", default=None,
        help="Cumulative audit ledger (reviews/manuscript-gate-<date>/audited.yaml). "
             "Subjects already audited under an unchanged fingerprint are skipped, so "
             "the next round drains the next slice of the pool instead of re-reading "
             "the same one. They stay in the denominator.")
